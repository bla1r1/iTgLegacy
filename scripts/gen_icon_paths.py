#!/usr/bin/env python3
"""Write src/Views/TGIconPaths.m from scripts/icon_picks.txt.

  scripts/gen_icon_paths.py <@mdi/js package dir> <@fortawesome/fontawesome-free package dir>

Each line of the picks file is `row name source glyph`, source being mdi,
fa or ours (ours stays drawn by TGIcons and is skipped here).
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mdi_dir, fa_dir = sys.argv[1], sys.argv[2]
mdi_js = open(os.path.join(mdi_dir, 'mdi.js')).read()

def mdi(name):
    m = re.search(r'export var %s = "([^"]+)"' % re.escape(name), mdi_js)
    if not m:
        sys.exit('no MDI icon ' + name)
    return m.group(1), 24, 24, 0

def fa(name):
    for style in ('solid', 'regular'):
        path = os.path.join(fa_dir, 'svgs', style, name + '.svg')
        if os.path.exists(path):
            svg = open(path).read()
            w, h = re.search(r'viewBox="0 0 (\d+) (\d+)"', svg).groups()
            d = re.search(r'<path[^>]+d="([^"]+)"', svg).group(1)
            # MDI draws inside 20 of its 24 units; FA fills its box, so it
            # gets the same margin (in 24ths) to sit at the same size.
            return d, int(w), int(h), 2
    sys.exit('no Font Awesome icon ' + name)

rows, seen = [], set()
for line in open(os.path.join(root, 'scripts', 'icon_picks.txt')):
    parts = line.split()
    if len(parts) < 3 or line.startswith('#') or parts[2] == 'ours':
        continue
    name, source, glyph = parts[1], parts[2], parts[3]
    if name in seen:
        continue
    seen.add(name)
    d, w, h, pad = (mdi if source == 'mdi' else fa)(glyph)
    rows.append((name, d, w, h, pad, source, glyph))

out = ['// Generated by scripts/gen_icon_paths.py from scripts/icon_picks.txt - do not edit.',
       '// Material Design Icons: Apache 2.0. Font Awesome Free 6.5.1 icons: CC BY 4.0.',
       '#import "TGIconPaths.h"', '#include <string.h>', '',
       'static const TGIconPath kPaths[] = {']
for name, d, w, h, pad, source, glyph in sorted(rows):
    out.append('\t{"%s", %d, %d, %d, "%s"},   // %s %s' % (name, w, h, pad, d, source, glyph))
out += ['};', '',
        'const TGIconPath *TGIconPathNamed(const char *name) {',
        '\tif (!name)', '\t\treturn NULL;',
        '\tfor (size_t i = 0; i < sizeof(kPaths) / sizeof(kPaths[0]); i++)',
        '\t\tif (strcmp(kPaths[i].name, name) == 0)', '\t\t\treturn &kPaths[i];',
        '\treturn NULL;', '}', '',
        'size_t TGIconPathCount(void) {', '\treturn sizeof(kPaths) / sizeof(kPaths[0]);', '}', '',
        'const TGIconPath *TGIconPathAt(size_t index) {',
        '\treturn index < TGIconPathCount() ? &kPaths[index] : NULL;', '}', '']
open(os.path.join(root, 'src', 'Views', 'TGIconPaths.m'), 'w').write('\n'.join(out))
print(len(rows), 'icons')
